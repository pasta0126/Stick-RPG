HEIGHT = 7
SPACING = 1


def glyph(ch):
    ch = ch.upper()
    return GLYPHS.get(ch, GLYPHS["?"])


def text_width(s):
    w = 0
    for ch in s:
        w += len(glyph(ch)[0]) + SPACING
    return max(0, w - SPACING)


def draw(put, s, x, y, color):
    """put(x, y, color) para cada píxel encendido."""
    cx = x
    for ch in s:
        g = glyph(ch)
        for j, row in enumerate(g):
            for i, c in enumerate(row):
                if c == "#":
                    put(cx + i, y + j, color)
        cx += len(g[0]) + SPACING
    return cx
